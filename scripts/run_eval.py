"""Verify every trajectory and write results/metrics.json and results/report.md.

    python scripts/run_eval.py              # recompute and write
    python scripts/run_eval.py --check      # recompute and fail if committed results differ, then gate (CI)
    python scripts/run_eval.py --summary    # print headline numbers from results/metrics.json
    python scripts/run_eval.py --runs-only  # score whatever is in data/runs into results/cloud/ (cloud pipeline)

Recomputing re-applies each committed patch to a fresh checkout and runs the hidden tests, so CI checks
the numbers by replaying them, not by trusting them. The gate fails if the harness controls break
(reference fix not 100%, empty patch not 0%) or if the main agent drops below the floor set once from
the measured run.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sweval.evaluate import evaluate  # noqa: E402

OUT = ROOT / "results"
MAIN = "gemma4-e2b.workflow"
FLOORS = {"main_resolved": 0.4, "main_minus_oneshot": 0.1}  # set once from the measured run (0.436, +0.154)
CEILINGS = {"main_regressions": 2}


def pct(r: dict | None) -> str:
    if not r:
        return "n/a"
    return f"{r['rate'] * 100:.1f}% ({r['k']}/{r['n']}, {r['ci95'][0] * 100:.1f}-{r['ci95'][1] * 100:.1f}%)"


def report(m: dict) -> str:
    s = m["suite"]
    L = ["# Evaluation report (generated by scripts/run_eval.py, do not edit)", "",
         (f"{s['tasks']} synthetic issues planted in the fictional Tallowmere Freight codebase "
          f"({s['files']} modules). Kinds: {s['by_kind']}; split: {s['by_split']}. A task is resolved when "
          "the issue's hidden test, the hidden whole-package regression suite and the visible tests all pass. Rates show k/n and a Wilson 95% interval. "
          "All runs on CPU with 4-bit weights; times depend on machine load."), "",
         f"Budgets per task: {m['limits']}", "",
         ("| Config | Mode | Resolved | Issue test only | Named | Symptom | Multi-step | Patch applied | Ran tests | "
          "p50 s | p50 tool calls |"),
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in m["configs"].items():
        k = c["by_kind"]
        cost = c.get("cost", {})
        L.append(f"| {name} | {c['mode']} | {pct(c['resolved'])} | {pct(c['issue_test_only'])} | {pct(k.get('named'))} | {pct(k.get('symptom'))} | "
                 f"{pct(k.get('multi'))} | {pct(c['patch_applied'])} | {pct(c['ran_tests'])} | "
                 f"{cost.get('seconds_p50', '-')} | {cost.get('tool_calls_p50', '-')} |")
    L += ["", "## Paired comparisons (same tasks, exact McNemar test)", "",
          "| Comparison | Tasks | Both solved | Only first | Only second | p |", "|---|---|---|---|---|---|"]
    L += [f"| {k} | {p['n']} | {p['both']} | {p['only_first']} | {p['only_second']} | {p['mcnemar_p']} |"
          for k, p in m["paired"].items()]
    L += ["", "## Why tasks failed (one primary reason each)", ""]
    for name, c in m["configs"].items():
        if c["mode"] != "baseline":
            L.append(f"- {name}: {c['failures'] or 'none'}; stop reasons {c['stop']}; invalid replies "
                     f"{c['invalid_replies']}; calls to tools that do not exist {c['unknown_tool_calls']}; failed "
                     f"tool calls {c['failed_tool_calls']}; regressions {c['regressions']}; patches touching tests "
                     f"{c['touched_tests']}")
    L += ["", "## Split check (dev was used while writing the prompt; test was not)", ""]
    for name, c in m["configs"].items():
        if c["mode"] != "baseline":
            L.append(f"- {name}: dev {pct(c['by_split'].get('dev'))}, test {pct(c['by_split'].get('test'))}")
    cfgs = [c for c in m["configs"] if m["configs"][c]["mode"] != "baseline"]
    L += ["", "## Per task", "", "| Task | Kind | " + " | ".join(cfgs) + " |", "|---|---|" + "---|" * len(cfgs)]
    from sweval.tasks import get

    for tid, row in m["per_task"].items():
        L.append(f"| {tid} | {get(tid)['kind']} | " + " | ".join("yes" if row.get(c) else "-" for c in cfgs) + " |")
    return "\n".join(L) + "\n"


def gate(m: dict) -> list[str]:
    c = m["configs"]
    bad = []
    if c["oracle"]["resolved"]["rate"] != 1.0:
        bad.append("harness: reference patches no longer resolve every task")
    if c["noop"]["resolved"]["rate"] != 0.0:
        bad.append("harness: an empty patch resolves a task (hidden test does not catch the bug)")
    main = c.get(MAIN)
    if main is None:
        return [*bad, f"no runs for {MAIN}"]
    if main["resolved"]["rate"] < FLOORS["main_resolved"]:
        bad.append(f"{MAIN} resolved {main['resolved']['rate']} < floor {FLOORS['main_resolved']}")
    one = c.get("gemma4-e2b.oneshot")
    if one and main["resolved"]["rate"] - one["resolved"]["rate"] < FLOORS["main_minus_oneshot"]:
        bad.append("agent loop no longer beats the one-shot control by the floor margin")
    if main["regressions"] > CEILINGS["main_regressions"]:
        bad.append(f"{MAIN} regressions {main['regressions']} > {CEILINGS['main_regressions']}")
    return bad


def dump(m: dict) -> str:
    return json.dumps(m, indent=1, sort_keys=False) + "\n"


def main() -> int:
    args = set(sys.argv[1:])
    if "--summary" in args:
        m = json.loads((OUT / "metrics.json").read_text())
        for name, c in m["configs"].items():
            print(f"{name:24s} resolved {pct(c['resolved'])}")
        for k, p in m["paired"].items():
            print(f"{k:24s} only first {p['only_first']}, only second {p['only_second']}, p={p['mcnemar_p']}")
        return 0
    m = evaluate()
    if "--runs-only" in args:
        (OUT / "cloud").mkdir(parents=True, exist_ok=True)
        (OUT / "cloud" / "metrics.json").write_text(dump(m))
        print(report(m))
        return 0
    if "--check" in args:
        same = (OUT / "metrics.json").read_text() == dump(m) and (OUT / "report.md").read_text() == report(m)
        if not same:
            print("results/ differ from a fresh replay; run scripts/run_eval.py and commit")
            return 1
    else:
        OUT.mkdir(exist_ok=True)
        (OUT / "metrics.json").write_text(dump(m))
        (OUT / "report.md").write_text(report(m))
    bad = gate(m)
    for b in bad:
        print("GATE FAIL:", b)
    print("gate:", "FAIL" if bad else "pass")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
